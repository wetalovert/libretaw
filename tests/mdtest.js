const fs=require('fs');const vm=require('vm');
const s=fs.readFileSync('/tmp/main.js','utf8');
const block=s.slice(s.indexOf('// ===== Markdown в сообщениях ====='),s.indexOf('// ===== Polls ====='));
const sb={};vm.createContext(sb);vm.runInContext(block,sb);
const H=t=>vm.runInContext('mdHtml('+JSON.stringify(t)+')',sb);
let pass=0,fail=0;const ok=(c,m)=>{if(c){pass++;console.log('  ok  ',m)}else{fail++;console.log('  FAIL',m,'\n   got:',JSON.stringify(c))}};
ok(H('**жирный**').includes('<b>жирный</b>'),'bold');
ok(H('*курс* и _курс2_').includes('<i>курс</i>')&&H('*курс* и _курс2_').includes('<i>курс2</i>'),'italic with * and _');
ok(H('~~зачёркнуто~~').includes('<s>зачёркнуто</s>'),'strikethrough');
ok(H('`x = 1 **не жирный**`').includes('<code>x = 1 **не жирный**</code>'),'inline code is not formatted inside');
ok(H('```\n**тут** <b>\n```').includes('<pre><code>**тут** &lt;b&gt;</code></pre>'),'code block keeps content literal and escaped');
ok(H('# Заголовок').includes('<h3>Заголовок</h3>'),'heading');
ok(H('> цитата').includes('<blockquote>цитата</blockquote>'),'quote');
ok(H('- один\n- два').includes('<ul><li>один</li><li>два</li></ul>'),'bullet list');
ok(H('1. первый\n2. второй').includes('<ol><li>первый</li><li>второй</li></ol>'),'numbered list');
ok(H('[сайт](https://example.com)').includes('<a href="https://example.com" target="_blank" rel="noopener noreferrer">сайт</a>'),'https link');
ok(!H('[клик](javascript:alert(1))').includes('<a'),'javascript: link is refused');
ok(!H('[x](data:text/html,hi)').includes('<a'),'data: link is refused');
ok(!H('<img src=x onerror=alert(1)>').includes('<img'),'raw HTML is escaped, not rendered');
ok(H('<script>alert(1)</script>').includes('&lt;script&gt;'),'script tag escaped');
ok(H('a\nb').includes('a<br>b'),'line breaks kept');
ok(H('2 * 3 * 4 = 24').indexOf('<i>')<0,'lone asterisks are not turned into italics');
ok(H('"кавычки" & амперсанд').includes('&amp;'),'ampersand escaped');
ok(!H('{color:javascript}x{/color}').includes('style="color'),'unknown colour is not applied');
ok(H('{dim}тихий{/dim}').includes('opacity:.55'),'custom: dim');
ok(H('{big}крупный{/big}').includes('font-size:1.35em'),'custom: big');
ok(H('{spoiler}секрет{/spoiler}').includes('class="spl"'),'custom: spoiler');
ok(H('{rainbow}радуга{/rainbow}').includes('background-clip:text'),'custom: rainbow');
ok(H('{dim}<script>alert(1)</script>{/dim}').includes('&lt;script&gt;'),'custom: HTML stays escaped inside formatting');
console.log(`\nresult: ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
